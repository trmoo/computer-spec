  // ⑤ AMD Ryzen AI — 예) Ryzen AI 9 HX 370, Ryzen AI 7 350, Ryzen AI Max+ 395
  if ((m = m0.match(/^ryzen\s*ai\s*(max\+?)?\s*([3579])?\s*(hx|pro)?\s*(\d)(\d{2})$/i))) {
    const [, 맥스, 등급, 접r, 시리즈, 번호] = m;
    const 조각들 = [조각('Ryzen AI', '브랜드', 'AMD 가 2024년부터 쓰는 이름. 강한 NPU(AI 전용 장치)를 넣었다는 뜻.', 'brand')];
    if (맥스) 조각들.push(조각(맥스, '등급', 'Max·Max+ — 아주 강한 내장 그래픽을 넣은 최상위 칩.', 'tier'));
    if (등급) 조각들.push(조각(등급, '등급', `${등급말[등급]}.`, 'tier'));
    if (접r) 조각들.push(조각(접r.toUpperCase(), '표시', 접r.toUpperCase() === 'HX' ? 'HX — 이 시리즈 안에서 가장 성능이 높은 모델. 인텔 HX(55W 이상)와 달리 기본 전력은 28W 안팎이다.' : 'PRO — 회사용 관리·보안 기능을 더한 모델.', 'suffix'));
    조각들.push(조각(시리즈, '시리즈(세대)', `${시리즈}00 시리즈 — ${시리즈 === '3' ? '2024~2025년' : '해부기가 아직 모르는 시리즈'}.`, 'gen'));
    조각들.push(조각(번호, '제품 번호', '같은 시리즈 안에서의 위치. 클수록 좋다.', 'sku'));
    return { ok: true, 회사: 'AMD', 구조: 'x86', 요약: `AMD Ryzen AI ${맥스 || ''}${등급 || ''} · ${시리즈}00 시리즈`, 조각들, 알림: ['AMD 도 인텔과 같은 x86 구조라 윈도우 프로그램과 게임이 그대로 돌아갑니다.'] };
  }

  // ⑥ AMD Ryzen — 예) Ryzen 7 7840U, Ryzen 5 7530U, Ryzen 7 8845HS, Ryzen 7 5800H
  if ((m = m0.match(/^ryzen\s*([3579])\s*(?:pro\s*)?(\d)(\d)(\d)(\d)([a-z]{0,3})$/i))) {
    const [, 등급, d1, d2, d3, d4, 접r] = m;
    const 접 = 접r.toUpperCase();
    const 노트북접 = ['U', 'H', 'HS', 'HX', 'C'].includes(접);
    const 알림 = [];
    if (!노트북접) 알림.push('이 접미사는 데스크톱용입니다. 노트북에서는 볼 수 없습니다.');
    const 조각들 = [
      조각('Ryzen', '브랜드', 'AMD 의 대표 라인(2017년~).', 'brand'),
      조각(등급, '등급', `${등급말[등급]}. Ryzen 3 < 5 < 7 < 9.`, 'tier'),
    ];
    // 2023년부터 AMD 노트북 칩은 네 자리 숫자마다 뜻이 정해져 있다(연도·시장·설계·위치).
    if ((d1 === '7' || d1 === '8') && 노트북접) {
      const 아키 = { 1: 'Zen 1(가장 오래된 설계)', 2: 'Zen 2', 3: 'Zen 3', 4: 'Zen 4' }[d3] || `Zen ${d3}`;
      const 시장 = { 1: '애슬론 실버', 2: '애슬론 골드', 3: '라이젠 3', 4: '라이젠 3', 5: '라이젠 5', 6: '라이젠 5', 7: '라이젠 7', 8: '라이젠 7·9', 9: '라이젠 9' }[d2];
      조각들.push(
        조각(d1, '출시 연도', `${d1 === '7' ? '2023' : '2024'}년 제품군.`, 'gen'),
        조각(d2, '시장 구분', `${시장}급.`, 'tier'),
        조각(d3, '설계(아키텍처)', `${아키}. ⚠ 같은 7000번대라도 이 숫자가 작으면 옛 설계다(7530U 는 Zen 3, 7840U 는 Zen 4).`, 'arch'),
        조각(d4, '위치', d4 === '5' ? '같은 무리 안에서 윗급.' : '같은 무리 안에서 아랫급.', 'sku'),
      );
      if (Number(d3) <= 3) 알림.push(`앞자리는 ${d1}000번대지만 셋째 숫자 ${은는(d3)} 옛 설계(Zen ${d3})라는 뜻입니다. 숫자 앞자리만 보고 최신이라 믿으면 안 됩니다.`);
    } else {
      const 연도 = { 1: '2018년', 2: '2019년', 3: '2020년', 4: '2020~2021년', 5: '2021년', 6: '2022년', 7: '2023년', 8: '2024년', 9: '2024~2025년' }[d1] || '';
      조각들.push(
        조각(d1, '세대(시리즈)', `${d1}000 시리즈 — ${연도} 무렵. 클수록 새 제품.`, 'gen'),
        조각(d2 + d3 + d4, '제품 번호', '같은 시리즈 안에서의 위치. 클수록 좋다.', 'sku'),
      );
    }
    조각들.push(접미사조각(접, 접r));
    return { ok: true, 회사: 'AMD', 구조: 'x86', 요약: `AMD Ryzen ${등급} · ${d1}000번대 · ${접미사사전[접]?.뜻 || 접 || '접미사 없음'}`, 조각들, 알림 };
  }

  // ⑦ 애플 M — 예) M4, M4 Pro, M3 Max
  if ((m = m0.match(/^m\s*(\d)\s*(pro|max|ultra)?$/i))) {
    const [, 세대, 등급r] = m;
    const 등급 = 등급r ? 등급r[0].toUpperCase() + 등급r.slice(1).toLowerCase() : '';
    return {
      ok: true, 회사: '애플', 구조: 'ARM',
      요약: `애플 M${세대}${등급 ? ' ' + 등급 : ''}`,
      조각들: [
        조각('M', '브랜드', '애플이 직접 설계한 맥(Mac)용 칩(2020년~). 스마트폰과 같은 ARM 구조라 전기를 적게 쓴다.', 'brand'),
        조각(세대, '세대', `M${세대} — ${애플세대연도[세대] || '해부기가 아직 모르는 세대'}. 숫자가 클수록 새 칩.`, 'gen'),
        조각(등급 || '(기본)', '등급', '기본 < Pro < Max < Ultra. 코어와 그래픽이 점점 많아진다.', 'tier'),
      ],
      알림: ['맥은 macOS 를 쓰므로 윈도우 전용 프로그램(일부 학교·공공 프로그램, 한글 등)이 되는지 먼저 확인하세요.'],
    };
  }

  // ⑧ 퀄컴 스냅드래곤 X — 예) Snapdragon X Elite, Snapdragon X Plus, Snapdragon X2 Elite
  if ((m = m0.match(/^(?:qualcomm\s*)?snapdragon\s*(x\d?)\s*(elite|plus)?/i))) {
    return {
      ok: true, 회사: '퀄컴', 구조: 'ARM',
      요약: `퀄컴 Snapdragon ${m[1].toUpperCase()} ${m[2] || ''}`.trim(),
      조각들: [
        조각('Snapdragon', '브랜드', '스마트폰 칩으로 유명한 퀄컴의 노트북용 칩(2024년~).', 'brand'),
        조각(m[1].toUpperCase(), '시리즈', 'X 시리즈 — 윈도우 노트북용.', 'gen'),
        조각(m[2] ? m[2][0].toUpperCase() + m[2].slice(1).toLowerCase() : '(기본)', '등급', 'Plus < Elite.', 'tier'),
      ],
      알림: ['ARM 구조라 배터리가 아주 오래갑니다. 대신 일부 게임·프로그램·장치(프린터 드라이버 등)가 실행되지 않을 수 있으니 쓰려는 프로그램을 먼저 확인하세요.'],
    };
  }

  return 모름(모델);
