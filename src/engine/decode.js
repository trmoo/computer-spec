// 윈도우 시스템 정보에 찍히는 군더더기를 걷어 내고 모델 부분만 남긴다.
export function 다듬기(입력) {
  let t = String(입력 || '');
  // 클럭 먼저 떼어 둔다 (예: "@ 2.50GHz", "   1.70 GHz")
  const 클럭맞음 = t.match(/(\d+(?:\.\d+)?)\s*GHz/i);
  const 클럭 = 클럭맞음 ? Number(클럭맞음[1]) : null;
  t = t.replace(/@?\s*\d+(?:\.\d+)?\s*GHz/gi, ' ');
  t = t.replace(/\((?:R|TM|C)\)|®|™/gi, ' ');
  t = t.replace(/\b\d{1,2}(?:st|nd|rd|th)\s+Gen(?:eration)?\b/gi, ' ');
  t = t.replace(/\bw\/.*$/i, ' ');                 // "w/ Radeon 780M Graphics"
  t = t.replace(/\bwith\s+.*graphics.*$/i, ' ');   // "with Radeon Graphics"
  t = t.replace(/\b(?:CPU|Processor|Mobile)\b/gi, ' ');
  t = t.replace(/\s+/g, ' ').trim();
  return { 모델: t, 클럭 };
}

function 조각(글, 이름, 설명, 색) {
  return { 글, 이름, 설명, 색 };
}

function 접미사조각(접, 글 = 접) {
  const 뜻 = 접미사사전[접];
  if (!뜻) return 조각(글 || '(없음)', '접미사', '이 글자는 해부기가 아직 모릅니다.', 'suffix');
  return 조각(글 || '(없음)', '접미사', `${뜻.뜻} — ${뜻.설명}`, 'suffix');
}

// 해부 결과: { ok, 회사, 요약, 조각들:[{글,이름,설명,색}], 알림:[...], 클럭 }
export function 해부(입력) {
  const { 모델, 클럭 } = 다듬기(입력);
  const 결과 = 해부모델(모델);
  if (클럭 != null && 결과.ok) {
    결과.조각들.push(조각(`${클럭}GHz`, '클럭', `1초에 약 ${클럭 * 10}억 번 박자를 맞춰 일한다. 같은 회사·같은 세대 안에서 견줄 때만 「높을수록 빠르다」가 대체로 맞다.`, 'clock'));
    결과.클럭 = 클럭;
  }
  결과.입력 = 모델;
  return 결과;
}

