import { 노트북들, 목적경고 } from '../data/laptops.js';
import { 최소글자, 글자수 } from '../data/activities.js';
import { 내기준점수, 만원 } from './calc.js';
import { 이가만, 을를만, 은는만 } from '../lib/josa.js';

// 까닭에 기준을 들었는지 알아보는 낱말들. 기준 이름별로 묶어 「어느 기준을 들었는지」로 알려 준다.
export const 기준낱말 = {
  가격: ['가격', '예산', '값', '만 원', '만원', '비싸', '저렴', '싸'],
  성능: ['성능', 'CPU', '코어', '램', 'RAM', '그래픽', 'RTX', '빠르', '느리'],
  화면: ['화면', '해상도', '인치', '주사율', 'Hz', 'OLED'],
  무게: ['무게', 'kg', '가볍', '가벼', '무겁', '무거', '들고'],
  발열: ['발열', '뜨거', '뜨겁'],
  소음: ['소음', '시끄', '조용', '팬'],
  배터리: ['배터리', '충전', '시간'],
  '연결(포트)': ['포트', '연결', '단자', 'USB', 'HDMI', '썬더볼트'],
  'A/S': ['A/S', 'AS', '서비스', '수리'],
};

export function 든기준찾기(글) {
  const t = String(글 || '');
  return Object.entries(기준낱말).filter(([, 낱말들]) => 낱말들.some((w) => t.includes(w))).map(([이름]) => 이름);
}

export function 점수표(순서) {
  return 노트북들
    .map((n) => ({ id: n.id, 이름: n.이름, 점수: 내기준점수(n.평점, 순서) }))
    .sort((a, b) => b.점수 - a.점수);
}

// 조건에 걸리는 까닭 목록 (예산·무게·목적)
export function 조건점검(노트북, m) {
  const 걸림 = [];
  if (m.예산 && 노트북.가격 > m.예산) 걸림.push(`예산 초과(${만원(노트북.가격 - m.예산)} 넘음)`);
  if (m.최대무게 && 노트북.무게 > m.최대무게) 걸림.push(`무게 초과(${노트북.무게}kg)`);
  for (const id of m.목적 || []) {
    const 경고 = 목적경고(id, 노트북);
    if (경고) 걸림.push(경고);
  }
  return 걸림;
}

// 되먹임 목록: [{ 종류: 'good' | 'warn' | 'tip', 글 }]
export function 미션점검(m, 순서) {
  const 말 = [];
  const 고른 = 노트북들.find((n) => n.id === m?.선택);
  if (!고른) {
    말.push({ 종류: 'warn', 글: '아직 노트북을 고르지 않았습니다. 비교표에서 하나를 고르세요.' });
    return 말;
  }
  if (!(m.목적 || []).length && !String(m.목적글 || '').trim()) {
    말.push({ 종류: 'tip', 글: '사용 목적을 고르지 않았습니다. 목적을 정하면 맞지 않는 노트북에 ⚠ 표시가 붙습니다.' });
  }

  const 걸림 = 조건점검(고른, m);
  if (걸림.length) {
    말.push({ 종류: 'warn', 글: `${고른.이름}${은는만(고른.이름)} 내가 정한 조건과 어긋납니다: ${걸림.join(' · ')}. 그래도 고른다면 까닭에 그 이유를 적어 주세요.` });
  } else {
    말.push({ 종류: 'good', 글: `${고른.이름}${은는만(고른.이름)} 내가 정한 예산·무게·목적 조건을 모두 만족합니다.` });
  }

  const 표 = 점수표(순서);
  const 일등 = 표[0];
  const 내점 = 표.find((x) => x.id === 고른.id);
  if (일등.id === 고른.id) {
    말.push({ 종류: 'good', 글: `내 기준 순위로 셈한 점수도 ${고른.이름}${이가만(고른.이름)} 1위(${내점.점수}점)입니다.` });
  } else {
    말.push({ 종류: 'tip', 글: `내 기준 점수 1위는 ${일등.이름}(${일등.점수}점)이고, 고른 노트북은 ${내점.점수}점입니다. 점수보다 더 중요한 까닭이 있었다면 그 까닭이 글에 드러나 있나요?` });
  }

  const 이유 = String(m.이유 || '');
  if (글자수(이유) < 최소글자.선택이유) {
    말.push({ 종류: 'warn', 글: `고른 까닭을 ${최소글자.선택이유}자 이상 써 주세요. (지금 ${글자수(이유)}자)` });
  } else {
    const 든기준 = 든기준찾기(이유);
    if (든기준.length) {
      말.push({ 종류: 'good', 글: `까닭에 선택 기준(${든기준.join(', ')})${을를만(든기준[든기준.length - 1])} 들어 설명했습니다.` });
    } else 말.push({ 종류: 'tip', 글: '까닭에 선택 기준(가격·성능·무게·배터리 …)이 드러나지 않습니다. ① 에서 정한 기준과 이어서 써 보세요.' });
    if (!/[0-9]/.test(이유)) 말.push({ 종류: 'tip', 글: '사양의 숫자(무게 kg, 배터리 시간, 램 GB 등)를 들어 쓰면 더 설득력이 있습니다.' });
  }

  if (글자수(m.포기) < 최소글자.포기) {
    말.push({ 종류: 'warn', 글: `이 노트북을 고르며 포기한 것을 ${최소글자.포기}자 이상 써 주세요. 모든 기준을 다 갖춘 노트북은 없습니다.` });
  }
  return 말;
}
