export function 목적경고(목적id, 노트북) {
  const n = 노트북;
  switch (목적id) {
    case 'pen': return n.펜 ? null : '펜·터치를 쓸 수 없음';
    case 'game': return n.외장 ? null : (n.구조 === 'ARM' ? '외장 그래픽 없음 · ARM 이라 일부 게임 실행 안 됨' : '외장 그래픽 없음');
    case 'ai3d': return n.외장 ? null : '외장 그래픽 없음';
    case 'video': return n.외장 || n.평점.perf >= 4 ? null : '영상 편집에는 성능이 부족할 수 있음';
    case 'carry': return n.무게 <= 1.6 ? null : `${n.무게}kg — 매일 들고 다니기엔 무거움`;
    case 'code': return n.구조 === 'ARM' ? '일부 개발 도구가 ARM 에서 안 될 수 있음 — 확인 필요' : null;
    default: return null;
  }
}

