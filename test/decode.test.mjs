  확인('M4 Pro 등급', 조각(m, '등급'), 'Pro');
  확인('M3 기본 등급', 조각(해부('M3'), '등급'), '(기본)');
  const q = 해부('Snapdragon X Elite');
  확인('스냅드래곤 구조', q.구조, 'ARM');
  참('호환성을 알린다', q.알림.some((a) => a.includes('프로그램')));
