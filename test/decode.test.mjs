묶음('모르는 것은 모른다고 한다');
for (const 글 of ['', '펜티엄', 'i7-99999Z', 'Core i7', 'GeForce RTX 4060', 'Core Ultra 7']) {
  참(`「${글}」 은 풀지 않는다`, !해부(글).ok);
}
참('모를 때 예시를 알려 준다', 해부('abc').알림.some((a) => a.includes('예시')));
확인('모를 때 조사: 「abc」는', 해부('abc').알림[0].startsWith('「abc」는'), true);
확인('모를 때 조사: 「펜티엄」은', 해부('펜티엄').알림[0].startsWith('「펜티엄」은'), true);

묶음('화면의 예시는 모두 풀린다');
