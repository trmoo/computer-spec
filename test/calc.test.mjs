import { 묶음, 확인, 참, 가깝다 } from './harness.mjs';
import { 인치를cm, 화면가로세로, ppi, 전송초, 시간말하기, 코어스레드, 내기준점수, 순위가중치, 반올림, 만원 } from '../src/engine/calc.js';
import { 대표CPU } from '../src/data/cpu.js';
import { 기준들 } from '../src/data/criteria.js';

묶음('인치 → cm (학습지 표의 값과 같아야 한다)');
가깝다('13.3인치 = 33.78cm', 인치를cm(13.3), 33.78, 0.005);
가깝다('14인치 = 35.56cm', 인치를cm(14), 35.56, 0.005);
가깝다('15.6인치 = 39.62cm', 인치를cm(15.6), 39.62, 0.005);
가깝다('17.3인치 = 43.94cm', 인치를cm(17.3), 43.94, 0.005);

묶음('화면 가로·세로');
{
  const a = 화면가로세로(14, 16, 9);
  const b = 화면가로세로(14, 16, 10);
  가깝다('14인치 16:9 세로 ≈ 17.4', a.세로, 17.43, 0.01);
  가깝다('14인치 16:10 세로 ≈ 18.8', b.세로, 18.85, 0.01);
  참('같은 인치면 16:10 이 세로가 더 길다', b.세로 > a.세로);
  참('같은 인치면 16:9 가 가로가 더 넓다', a.가로 > b.가로);
  가깝다('피타고라스: 가로² + 세로² = 대각선²', a.가로 ** 2 + a.세로 ** 2, a.대각 ** 2, 1e-9);
}

묶음('PPI');
가깝다('14인치 FHD ≈ 157', ppi(1920, 1080, 14), 157.35, 0.01);
참('같은 크기면 4K 가 FHD 보다 촘촘하다', ppi(3840, 2160, 14) > ppi(1920, 1080, 14));
가깝다('4K 는 FHD 의 정확히 두 배 PPI', ppi(3840, 2160, 14) / ppi(1920, 1080, 14), 2, 1e-12);

묶음('전송 시간');
확인('10GB ÷ 10Gbps = 8초', 전송초(10, 10), 8);
확인('4GB ÷ 5Gbps = 6.4초', 반올림(전송초(4, 5), 3), 6.4);
확인('시간 말하기 — 8초', 시간말하기(8), '8초');
확인('시간 말하기 — 66.7초', 시간말하기(전송초(4, 0.48)), '1분 7초');
확인('시간 말하기 — 1시간 넘게', 시간말하기(4000), '1시간 6분');
확인('시간 말하기 — 1초 미만', 시간말하기(0.2 * 8 / 80), '0.02초');
확인('시간 말하기 — 딱 2분', 시간말하기(120), '2분');

묶음('코어와 스레드 — 대표 CPU 표가 셈과 맞는가');
for (const c of 대표CPU) {
  const r = 코어스레드(c);
  확인(`${c.이름} 코어`, r.코어, c.코어);
  확인(`${c.이름} 스레드`, r.스레드, c.스레드);
}

묶음('내 기준 점수');
{
  const 순서 = 기준들.map((c) => c.id);
  const 모두5 = Object.fromEntries(순서.map((id) => [id, 5]));
  const 모두1 = Object.fromEntries(순서.map((id) => [id, 1]));
  확인('모든 기준 5점이면 100점', 내기준점수(모두5, 순서), 100);
  확인('모든 기준 1점이면 20점', 내기준점수(모두1, 순서), 20);
  const 가중 = 순위가중치(순서);
  확인('1위 가중치 9', 가중[순서[0]], 9);
  확인('9위 가중치 1', 가중[순서[8]], 1);
  // 1위 기준만 5점이고 나머지 1점 — 1위가 바뀌면 점수가 달라져야 한다
  const 한쪽 = { ...모두1, [순서[0]]: 5 };
  참('1위 기준이 좋은 노트북은 그 기준을 1위로 둘 때 점수가 더 높다',
    내기준점수(한쪽, 순서) > 내기준점수(한쪽, [...순서.slice(1), 순서[0]]));
}

묶음('금액 표기');
확인('59만 원', 만원(590000), '59만 원');
확인('249만 원', 만원(2490000), '249만 원');
